// Regenerates src/common/countries.js from the ISO 3166-1 country list.
// Run by hand when the list changes: node scripts/generate-countries.js
// Output is committed; the app must not fetch a country list at runtime.
const fs = require('fs');
const path = require('path');

const SOURCE_URL =
  'https://raw.githubusercontent.com/lukes/ISO-3166-Countries-with-Regional-Codes/master/all/all.json';
const OUTPUT_PATH = path.join(__dirname, '..', 'src', 'common', 'countries.js');

async function main() {
  const response = await fetch(SOURCE_URL);

  if (!response.ok) {
    throw new Error(`Failed to fetch ${SOURCE_URL}: ${response.status}`);
  }

  const names = (await response.json())
    .map((country) => country.name)
    .filter(Boolean)
    .sort((a, b) => a.localeCompare(b, 'en'));

  if (names.length < 200) {
    throw new Error(`Expected at least 200 countries, got ${names.length}`);
  }

  const file = `// Generated by scripts/generate-countries.js: do not edit by hand.
// ISO 3166-1 English short names, ${SOURCE_URL}, ${new Date()
    .toISOString()
    .slice(0, 10)}.
// Stored verbatim in entity.location, so renaming one orphans existing rows.
const COUNTRIES = ${JSON.stringify(names, null, 2)};

export default COUNTRIES;
`;

  fs.writeFileSync(OUTPUT_PATH, file);
  console.log(`Wrote ${names.length} countries to ${OUTPUT_PATH}`);
}

main().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
